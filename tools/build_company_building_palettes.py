#!/usr/bin/env python3
"""Derive enemy roof/cloth colors from the eight original Company SVG masters.

Geometry, bone masonry, timber, metal and shadows remain identical. This edits
vector material tokens, never raster pixels. Run after changing a home master.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
# Only enameled roof planes, roof joints, cloth awnings and company marks.
# Neutral limewash, masonry/wood planes and shared ink outlines are untouched.
CLAY = {
    '#344f4b': '#51433e', '#304c45': '#51433e',
    '#6c9890': '#b77d62', '#4d7770': '#8b5c4e', '#88aaa0': '#c59679',
    '#a6b6a0': '#c7ad8c', '#587e71': '#9e735b',
    '#527e75': '#95634f', '#8bb0a1': '#c99a77', '#bed0b2': '#dac2a0',
    '#547d70': '#b7785f',
    '#7aa196': '#bd896c', '#537f73': '#996a54', '#9ebbad': '#d0ad8e',
    '#bbcab0': '#d4bc98', '#4b7666': '#936b51',
    '#729b8c': '#b98465', '#4d796a': '#92644e', '#a6bda6': '#ccb08a',
    '#bcc6a7': '#d0b995', '#36594b': '#5e493e', '#9eb69d': '#c29a77',
    '#587e66': '#9d7155', '#547d65': '#a47255',
}


def main() -> None:
    for name in ('town_center', 'house', 'barracks', 'resource_camp', 'archery_range', 'stable', 'blacksmith', 'siege_workshop'):
        source = ROOT / f'assets/buildings/company_{name}.svg'
        text = source.read_text()
        derived = re.sub(r'#[0-9a-fA-F]{6}', lambda m: CLAY.get(m.group().lower(), m.group()), text)
        derived = derived.replace('  <!-- Original Company', '  <!-- Enemy material variant, generated by tools/build_company_building_palettes.py.\n       Same geometry and neutral materials; clay roofs/cloth. -->\n  <!-- Original Company', 1)
        destination = source.with_stem(source.stem + '_enemy')
        destination.write_text(derived)
        print(destination.relative_to(ROOT))


if __name__ == '__main__':
    main()
